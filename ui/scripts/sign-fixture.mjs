/**
 * Signs a grant with a fixed key and a fixed scope, and writes the token to a
 * fixture the Rust side verifies.
 *
 * The browser signer in `src/lib/grants.ts` is a second implementation of
 * `shared/src/grants.rs`. Two implementations of one wire format drift, and this
 * one drifts *silently*: base64url padding, a field omitted from the payload, a
 * wrong domain separator in the key id, a number serialised as a float. None of
 * those surface as an error on this side. They surface as an owner issuing
 * grants that nothing accepts, with no indication of which half is wrong.
 *
 * So the format is pinned the way this repo already pins the Python/Rust schema
 * mirror in `test_schema_parity.py`: by making the other side check. This script
 * produces the artefact; `shared/tests/browser_grant_parity.rs` verifies it with
 * the real `verify_grant` and recomputes the key id with the real `key_id_for`.
 *
 *     npm run fixture        # regenerate after changing the signer
 *
 * The seed is RFC 8032's first Ed25519 test vector, committed deliberately. It
 * signs nothing real and is registered to no owner.
 */

import { webcrypto, createPrivateKey, createPublicKey } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { blake2b } from "blakejs";

// The encoding is reimplemented in these few lines rather than imported from
// `src/lib/grants.ts`. That is not duplication to tidy away: a fixture generated
// by importing the module under test would agree with that module by
// construction, which is the one failure this exists to catch. The independent
// reading is the point.
const b64url = (bytes) => Buffer.from(bytes).toString("base64url").replace(/=+$/, "");

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "..", "shared", "tests", "fixtures");

/** RFC 8032 test vector 1. 32 bytes. A test vector, not a key. */
const SEED_HEX = "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60";
/** The PKCS#8 wrapper WebCrypto and Node both want around a raw Ed25519 seed. */
const PKCS8_PREFIX = Buffer.from("302e020100300506032b657004220420", "hex");
const KEY_ID_DOMAIN = "kleos/device-key/v1";

const ISSUED_AT_MS = 1_700_000_000_000;
const TTL_SECS = 3600;
const NONCE = "0011223344556677";

/**
 * Every field of `Scope`, with the capability flags deliberately *on*. A fixture
 * of the default read-only scope would pass even if the signer dropped all seven
 * appended fields, since they are `#[serde(default)]` on the Rust side.
 */
const SCOPE = {
  agent_id: "chatgpt",
  owner_id: "owner-browser-parity",
  sources: ["mock", "agent"],
  entity_kinds: ["person", "project", "artifact", "organization", "topic"],
  not_before_ms: null,
  not_after_ms: null,
  max_sensitivity: "confidential",
  // Later than the token's own TTL on purpose, so the fixture exercises the
  // clamp in `verify_grant` (`grants.rs:196`) and not only the signature.
  expires_at_ms: 4_000_000_000_000,
  may_write: true,
  may_unseal: true,
  may_supersede_owner: false,
  write_sources: ["agent"],
  memory_kinds: ["episodic", "procedural", "tacit"],
  may_act: true,
  act_actions: ["attest.digest"],
};

const seed = Buffer.from(SEED_HEX, "hex");
const pkcs8 = Buffer.concat([PKCS8_PREFIX, seed]);

// Node's key objects derive the public key from the private one; WebCrypto has
// no equivalent. The last 32 bytes of the 44-byte SPKI encoding are the raw key.
const publicKey = createPublicKey(
  createPrivateKey({ key: pkcs8, format: "der", type: "pkcs8" }),
)
  .export({ format: "der", type: "spki" })
  .subarray(-32);

const keyIdInput = Buffer.concat([Buffer.from(KEY_ID_DOMAIN, "utf8"), publicKey]);
const keyId = Buffer.from(blake2b(keyIdInput, undefined, 32))
  .subarray(0, 16)
  .toString("hex");

const claims = {
  typ: "grant",
  key_id: keyId,
  scope: SCOPE,
  issued_at_ms: ISSUED_AT_MS,
  expires_at_ms: ISSUED_AT_MS + TTL_SECS * 1000,
  nonce: NONCE,
};

const payload = Buffer.from(JSON.stringify(claims), "utf8");
const privateKey = await webcrypto.subtle.importKey(
  "pkcs8",
  pkcs8,
  { name: "Ed25519" },
  false,
  ["sign"],
);
const signature = Buffer.from(await webcrypto.subtle.sign("Ed25519", privateKey, payload));
const token = `kgrant.v1.${b64url(payload)}.${b64url(signature)}`;

mkdirSync(OUT, { recursive: true });
const path = join(OUT, "browser_grant.json");
writeFileSync(
  path,
  JSON.stringify(
    {
      note:
        "Generated by ui/scripts/sign-fixture.mjs, verified by " +
        "shared/tests/browser_grant_parity.rs. Regenerate with `npm run fixture` " +
        "in ui/ -- and if that is ever necessary without an intended format " +
        "change, the signer has drifted and that is what the test is for.",
      seed_hex: SEED_HEX,
      public_key_hex: publicKey.toString("hex"),
      key_id: keyId,
      issued_at_ms: ISSUED_AT_MS,
      token,
      expect_scope: SCOPE,
      expect_clamped_expires_at_ms: claims.expires_at_ms,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${path}`);
console.log(`key_id ${keyId}`);
